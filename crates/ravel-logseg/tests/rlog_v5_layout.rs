/// A [`ByteSource`] that records every range it is asked for.
struct CountingSource<'a> {
    bytes: &'a [u8],
    reads: RefCell<Vec<(u64, u64)>>,
}

impl ByteSource for CountingSource<'_> {
    fn object_len(&self) -> u64 {
        self.bytes.object_len()
    }

    fn read(&self, start: u64, len: u64) -> Result<Cow<'_, [u8]>, LogSegError> {
        self.reads.borrow_mut().push((start, len));
        self.bytes.read(start, len)
    }
}

/// A version-4 object is refused with the typed `UnsupportedVersion(4)` on the
/// trailer alone: the footer, the directories and every page stay unread.
#[test]
fn v4_object_is_refused_as_unsupported_version() {
    let n = GOLDEN_V4.len();
    assert_eq!(u16::from_le_bytes([GOLDEN_V4[n - 8], GOLDEN_V4[n - 7]]), 4);
    assert_eq!(&GOLDEN_V4[n - 4..], b"RLG1");

    let source = CountingSource {
        bytes: GOLDEN_V4,
        reads: RefCell::new(Vec::new()),
    };
    match RlogReader::from_source(&source, &RlogConfig::default()) {
        Err(LogSegError::UnsupportedVersion(4)) => {}
        other => panic!(
            "expected UnsupportedVersion(4), got {:?}",
            other.map(|_| ())
        ),
    }
    assert_eq!(
        *source.reads.borrow(),
        vec![(n as u64 - 16, 16)],
        "only the trailer is read before the refusal"
    );

    assert!(matches!(
        open(GOLDEN_V4),
        Err(LogSegError::UnsupportedVersion(4))
    ));
    assert!(matches!(
        footer::open_from_suffix(&GOLDEN_V4[n - 16..], n as u64),
        Err(LogSegError::UnsupportedVersion(4))
    ));
}

/// Re-footers `object` with `footer`, keeping every section byte in place.
fn refooter(object: &[u8], footer: &LogFooter) -> Vec<u8> {
    let n = object.len();
    let footer_len = u32::from_le_bytes(object[n - 16..n - 12].try_into().expect("4 bytes"));
    let mut out = object[..n - 16 - footer_len as usize].to_vec();
    write_footer_and_trailer(&mut out, footer);
    out
}

/// A footer with a sort descriptor and a clustering generation decodes to the
/// same values, and the object still reads. The writer records neither, which
/// decodes as no descriptor and generation 0.
#[test]
fn footer_round_trips_the_sort_descriptor_and_generation() {
    let records = vec![record(0, "a", "x"), record(1, "b", "y")];
    let object = write(RlogWriter::new(RlogConfig::default(), identity()), &records);
    let written = open(&object).expect("open");
    assert_eq!(written.sort_descriptor, None);
    assert_eq!(written.clustering_generation, 0);

    let descriptor = SortDescriptor {
        bucket_width: SortBucketWidth::SixHours,
        key_columns: vec![
            SortKeyColumn {
                name: "region".into(),
                ty: SortKeyType::Str,
            },
            SortKeyColumn {
                name: "http.status".into(),
                ty: SortKeyType::I64,
            },
            SortKeyColumn {
                name: "cache.hit".into(),
                ty: SortKeyType::Bool,
            },
            SortKeyColumn {
                name: "trace.blob".into(),
                ty: SortKeyType::Bytes,
            },
        ],
    };
    let mut clustered = written.clone();
    clustered.sort_descriptor = Some(descriptor.clone());
    clustered.clustering_generation = 7;
    let rewritten = refooter(&object, &clustered);
    let decoded = open(&rewritten).expect("open clustered");
    assert_eq!(decoded.sort_descriptor, Some(descriptor.clone()));
    assert_eq!(decoded.clustering_generation, 7);
    assert_eq!(decoded, clustered);

    let cfg = RlogConfig::default();
    let reader = RlogReader::new(&rewritten, &cfg).expect("reader");
    let (rows, _) = reader.scan(&Predicate::And(vec![])).expect("scan");
    assert_eq!(rows.len(), records.len());

    // A cleared key: generation stays above zero, the descriptor goes.
    let mut cleared = written.clone();
    cleared.clustering_generation = 8;
    let decoded = open(&refooter(&object, &cleared)).expect("open cleared");
    assert_eq!(decoded.sort_descriptor, None);
    assert_eq!(decoded.clustering_generation, 8);

    // Generation 0 means no key was ever set, so a descriptor beside it is a
    // contradiction; so is a key list outside one to four columns.
    let mut at_zero = written.clone();
    at_zero.sort_descriptor = Some(descriptor.clone());
    assert!(matches!(
        open(&refooter(&object, &at_zero)),
        Err(LogSegError::Corrupted(_))
    ));
    for width in [0, 5] {
        let mut bad = clustered.clone();
        let key = SortKeyColumn {
            name: "k".into(),
            ty: SortKeyType::Str,
        };
        bad.sort_descriptor = Some(SortDescriptor {
            bucket_width: SortBucketWidth::OneDay,
            key_columns: vec![key; width],
        });
        assert!(
            matches!(
                open(&refooter(&object, &bad)),
                Err(LogSegError::Corrupted(_))
            ),
            "{width} key columns"
        );
    }
}

fn corrupted(r: Result<RlogBloomSection<'_>, LogSegError>, needle: &str) {
    match r {
        Err(LogSegError::Corrupted(m)) if m.contains(needle) => {}
        Err(other) => panic!("expected Corrupted about {needle}, got {other:?}"),
        Ok(s) => panic!(
            "expected Corrupted about {needle}, parsed covering {:?}",
            s.covered()
        ),
    }
}

/// The covered-column list is strictly ascending and names only columns the
/// object has. An unsorted list, a repeated id, and an id that is neither a
/// fixed column nor in FIELD_DIR are each refused as `Corrupted`.
#[test]
fn bloom_coverage_list_is_validated() {
    let records = vec![record(0, "a", "x")];
    let object = write(RlogWriter::new(RlogConfig::default(), identity()), &records);
    let dir = field_dir_of(&object);
    let region = dir
        .column("region", FieldType::Str)
        .expect("region")
        .column_id;
    let note = dir.column("note", FieldType::Str).expect("note").column_id;
    let max_cid = dir
        .entries()
        .iter()
        .map(|e| e.column_id)
        .max()
        .expect("cid");

    let mut builder = BloomBuilder::new(0);
    builder.insert(COL_BODY, b"x");
    let entries = vec![builder.finish_exact()];

    // The writer's own list parses, so the refusals below are about the list.
    let written = bloom_raw_of(&object);
    let ok = RlogBloomSection::parse(&written, &dir).expect("writer's BLOOM");
    let mut want = vec![COL_SEVERITY_TEXT, COL_BODY, note, region];
    want.sort_unstable();
    assert_eq!(ok.covered(), want.as_slice());
    let sorted = encode_rlog_bloom_section(&want, &entries);
    RlogBloomSection::parse(&sorted, &dir).expect("sorted list");

    let unsorted = encode_rlog_bloom_section(&[COL_BODY, COL_SEVERITY_TEXT], &entries);
    corrupted(RlogBloomSection::parse(&unsorted, &dir), "ascending");

    let duplicate = encode_rlog_bloom_section(&[COL_BODY, region, region], &entries);
    corrupted(RlogBloomSection::parse(&duplicate, &dir), "ascending");

    let past_field_dir = encode_rlog_bloom_section(&[COL_BODY, max_cid + 1], &entries);
    corrupted(RlogBloomSection::parse(&past_field_dir, &dir), "FIELD_DIR");

    let huge = encode_rlog_bloom_section(&[COL_BODY, u32::MAX], &entries);
    corrupted(RlogBloomSection::parse(&huge, &dir), "FIELD_DIR");
}
