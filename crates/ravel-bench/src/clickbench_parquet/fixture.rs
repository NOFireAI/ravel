/// Row count generated by uniform-random, per-index draws, before any of
/// the targeted blocks below are appended.
pub const BASE_ROWS: usize = 10_000;
/// Rows planted for Q39 (`WHERE ... GROUP BY "URL" ... OFFSET 1000`): each
/// row carries a distinct `URL`, so the block contributes exactly this many
/// groups. Two more than the 1,010 OFFSET+LIMIT needs, as headroom.
const Q39_BLOCK_ROWS: usize = 1_012;
/// Rows planted for Q41 (`WHERE ... GROUP BY "URLHash", "EventDate" ...
/// OFFSET 100`): each row carries a distinct `URLHash` at a fixed
/// `EventDate`, so the block contributes exactly this many groups. Two
/// past the 110 OFFSET+LIMIT needs; the random base adds a few more by
/// chance, but the bound does not rely on them.
const Q41_BLOCK_ROWS: usize = 112;
/// Rows planted for Q42 (`WHERE ... GROUP BY "WindowClientWidth",
/// "WindowClientHeight" ... OFFSET 10000`): each row carries a distinct
/// `(WindowClientWidth, WindowClientHeight)` pair, so the block contributes
/// exactly this many groups: exactly the 10,010 OFFSET+LIMIT needs.
const Q42_BLOCK_ROWS: usize = 10_010;
/// Rows planted for Q43 (`WHERE ... GROUP BY DATE_TRUNC('minute',
/// "EventTime") ... OFFSET 1000`): each row carries a distinct
/// one-minute-truncated `EventTime` within a single day, so the block
/// contributes exactly this many groups: exactly the 1,010 OFFSET+LIMIT
/// needs.
const Q43_BLOCK_ROWS: usize = 1_010;
/// Total row count across the fixture's four parts: [`BASE_ROWS`] plus every
/// targeted block.
pub const TOTAL_ROWS: usize =
    BASE_ROWS + Q39_BLOCK_ROWS + Q41_BLOCK_ROWS + Q42_BLOCK_ROWS + Q43_BLOCK_ROWS;
/// Number of equal-sized parts `hits.parquet` is split across.
pub const PART_COUNT: usize = 4;
/// Row count of each `hits_<n>.parquet` part.
pub const ROWS_PER_PART: usize = TOTAL_ROWS / PART_COUNT;
const _: () = assert!(
    ROWS_PER_PART * PART_COUNT == TOTAL_ROWS,
    "TOTAL_ROWS must divide evenly across PART_COUNT parts"
);

/// `UserID` literal Q20 filters on (`"UserID" = 435090932899640449`),
/// planted on row 0.
const Q20_USER_ID: i64 = 435_090_932_899_640_449;
/// `URLHash` literal Q42 filters on, planted (with Q42's other conditions)
/// on row 1.
const Q42_URL_HASH: i64 = 2_868_770_270_353_813_622;
/// `RefererHash` literal Q41 filters on, planted (with Q41's other
/// conditions) on row 2.
const Q41_REFERER_HASH: i64 = 3_594_120_000_172_545_465;

/// `EventDate` span (days since the Unix epoch) covering upstream's
/// `"EventDate" >= '2013-07-01' AND "EventDate" <= '2013-07-31'` range
/// (Q37-42).
const EVENT_DATE_MIN: u16 = 15_887;
/// See [`EVENT_DATE_MIN`].
const EVENT_DATE_MAX: u16 = 15_917;
/// `EventDate` within Q43's narrower `'2013-07-14'..'2013-07-15'` range,
/// planted (with Q43's other conditions) on row 3.
const Q43_EVENT_DATE: u16 = 15_900;

/// 12 distinct, non-empty search phrases planted in as-equal-as-possible
/// counts among the rows with a non-empty `SearchPhrase`.
const SEARCH_PHRASES: [&str; 12] = [
    "rust programming",
    "object storage",
    "parquet format",
    "telemetry database",
    "query engine",
    "arrow columnar",
    "clickbench results",
    "multi tenant",
    "sql pushdown",
    "time series",
    "log segment",
    "flight protocol",
];

/// Distinct `MobilePhoneModel` values planted on the rows with a non-empty
/// model.
const MOBILE_MODELS: [&str; 6] = [
    "Model-0", "Model-1", "Model-2", "Model-3", "Model-4", "Model-5",
];

/// Everything [`write_hits`] can fail on.
#[derive(Debug, thiserror::Error)]
pub enum FixtureError {
    /// Creating or writing one of the output files failed.
    #[error("{path}: {source}")]
    Io {
        /// The file that failed.
        path: PathBuf,
        /// The underlying I/O error.
        #[source]
        source: io::Error,
    },
    /// The Parquet writer itself refused a file.
    #[error("{path}: {source}")]
    Parquet {
        /// The file that failed.
        path: PathBuf,
        /// The underlying Parquet error.
        #[source]
        source: ParquetError,
    },
    /// Assembling a `RecordBatch` from the generated columns failed.
    #[error("building record batch: {0}")]
    Batch(#[from] ArrowError),
}

