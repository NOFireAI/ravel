//! Deterministic synthetic ClickBench fixture (ADR-2040, issue #2055 task
//! T5b). [`write_hits`] plants a 25-column, [`TOTAL_ROWS`]-row corpus across
//! four equal-sized parts (`hits_0.parquet`..`hits_3.parquet`) plus one
//! combined file (`hits.parquet`), so a later task's engines can mount
//! either shape under `suite.toml`'s table template. Every row is derived
//! only from a seed and its own index, so two runs with the same seed
//! produce byte-identical Parquet files.
//!
//! The column list is exactly the 25 distinct quoted identifiers referenced
//! across `benchmarks/clickbench/parquet/queries.sql` (verified by
//! `fn queries_sql_references_every_column` below): 4 as `Int64`, 3 as
//! `Int32`, 11 as `Int16`, `EventTime` as `Int64` (seconds, matching
//! upstream's `to_timestamp_seconds("EventTime")` queries), `EventDate` as
//! `UInt16` (days since the Unix epoch, matching `suite.toml`'s
//! `ravel.cast.EventDate = date-from-days` table option), and the 5
//! string-shaped columns as `Binary` with no UTF-8 annotation (matching
//! `suite.toml`'s `binary_as_string` table option).
//!
//! [`BASE_ROWS`] rows are generated by uniform-random draws (per-row, seeded
//! by index); four further blocks are planted on top for statements whose
//! `GROUP BY ... ORDER BY ... LIMIT 10 OFFSET <n>` shape the random base
//! alone cannot satisfy, because its OFFSET exceeds the number of distinct
//! groups the random rows happen to produce: Q39 (`Q39_BLOCK_ROWS` rows,
//! OFFSET 1000), Q41 (`Q41_BLOCK_ROWS` rows, OFFSET 100), Q42
//! (`Q42_BLOCK_ROWS` rows, OFFSET 10000), and Q43 (`Q43_BLOCK_ROWS` rows,
//! OFFSET 1000). Each block's rows satisfy that statement's `WHERE` by
//! construction and vary only the column(s) the statement groups by, so
//! every planted row is its own group and the group count equals the block
//! size. Q40 has the same OFFSET-1000 shape but is not planted: its `WHERE`
//! (`CounterID = 62 AND EventDate` in range `AND IsRefresh = 0`, with no
//! further restriction) already passes for roughly a quarter of
//! [`BASE_ROWS`]'s random rows (`CounterID = 62` at 30%, `IsRefresh = 0` at
//! 80%), and its `GROUP BY "TraficSourceID", "SearchEngineID", "AdvEngineID",
//! Src, Dst` key multiplies that row set out across 11 distinct
//! `TraficSourceID` values, 6 `SearchEngineID` values, and up to 500 distinct
//! `Dst` (`"URL"`) values, which is already far past 1,010 distinct groups
//! without any planting.
//!
//! Q28 and Q29 are not coverable by this fixture at all: both require a
//! `GROUP BY ... HAVING COUNT(*) > 100000` on a single `CounterID` value
//! (Q28) or a single `Referer` host (Q29), which demands one group holding
//! more rows than this fixture's entire row count. Both statements return
//! zero rows against every engine here; this fixture only exercises their
//! cardinality-zero agreement, never their `HAVING` clause.

